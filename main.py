"""Data Project 1 - reproducible text classification experiment.

This program follows the assignment workflow explicitly:

1. Load and validate the labelled data.
2. Create one fixed, stratified training/validation split.
3. Compare at least two algorithms and several parameter settings.
4. Run controlled feature ablations for the proposed innovation.
5. Record a real epoch-by-epoch MLP loss curve.
6. Save validation evidence without reading the official test set.

Run finalize_prediction.py after both parameter searches to select the final
configuration, refit it and write prediction.csv.

The experiment report is intentionally not generated by this script.
"""

