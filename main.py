@dataclass(frozen=True)
class ExperimentConfig:
    """All important experiment choices in one reproducible configuration."""

    seed: int = 42
    validation_size: float = 0.20
    word_features: int = 80_000
    char_features: int = 80_000
    subject_features: int = 10_000
    body_features: int = 40_000
    mlp_features: int = 12_000
    mlp_hidden_units: int = 64
    mlp_activation: str = "tanh"
    mlp_alpha: float = 0.01
    mlp_max_epochs: int = 30
    mlp_patience: int = 5
    batch_size: int = 128
    hybrid_char_weight: float = 0.85


