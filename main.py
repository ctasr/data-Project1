def create_directories() -> None:
    for directory in (PATHS.results, PATHS.figures, PATHS.models):
        directory.mkdir(exist_ok=True)


def extract_subject_and_body(text: str) -> tuple[str, str]:
    """Extract a newsgroup Subject header and a cleaned message body.

    This is deterministic preprocessing and never uses the target label.
    Keeping subject and body separately enables a controlled ablation study.
    """

    text = str(text).replace("\r\n", "\n")
    subject_match = re.search(r"(?im)^subject:\s*(.*)$", text)
    subject = subject_match.group(1).strip() if subject_match else ""

    blocks = re.split(r"\n\s*\n", text, maxsplit=1)
    body = blocks[1] if len(blocks) == 2 else text
    body = re.sub(
        r"(?im)^(from|subject|organization|lines|nntp-posting-host|"
        r"reply-to|distribution|keywords):.*$",
        " ",
        body,
    )
    body = re.sub(r"\s+", " ", body).strip()
    return subject, body


def add_structured_text_columns(frame: pd.DataFrame) -> pd.DataFrame:
    result = frame.copy()
    parsed = result["text"].astype(str).map(extract_subject_and_body)
    result[["subject", "body"]] = pd.DataFrame(parsed.tolist(), index=result.index)
    return result


def load_labelled_data() -> pd.DataFrame:
    """Load only the labelled dataset used during model development."""

    frame = pd.read_csv(PATHS.train_csv)
    if not {"text", "target"}.issubset(frame.columns):
        raise ValueError("train_data.csv must contain 'text' and 'target' columns")
    if frame[["text", "target"]].isna().any().any():
        raise ValueError("The labelled dataset contains missing text or labels")
    if frame["text"].duplicated().any():
        raise ValueError("The labelled dataset contains duplicate text")
    if set(frame["target"].unique()) != set(LABELS):
        raise ValueError("Expected integer labels from 0 to 9")
    return add_structured_text_columns(frame)


def load_official_test_data() -> pd.DataFrame:
    """Load the sealed official test set only after model selection."""

    frame = pd.read_csv(PATHS.test_csv)
    if "text" not in frame.columns or frame["text"].isna().any():
        raise ValueError("test_data_unlabeled.csv must contain non-missing 'text'")
    return add_structured_text_columns(frame)


def save_data_audit(labelled: pd.DataFrame) -> None:
    """Keep evidence that deterministic parsing neither drops nor relabels rows."""

    original = pd.read_csv(PATHS.train_csv)
    unchanged_rows = len(original) == len(labelled)
    unchanged_text = original["text"].reset_index(drop=True).equals(
        labelled["text"].reset_index(drop=True)
    )
    unchanged_targets = original["target"].reset_index(drop=True).equals(
        labelled["target"].reset_index(drop=True)
    )
    if not (unchanged_rows and unchanged_text and unchanged_targets):
        raise RuntimeError("Preprocessing altered source rows, text, or targets")
    audit = {
        "original_rows": len(original),
        "processed_rows": len(labelled),
        "removed_rows": len(original) - len(labelled),
        "missing_text_before": int(original["text"].isna().sum()),
        "missing_target_before": int(original["target"].isna().sum()),
        "duplicate_text_before": int(original["text"].duplicated().sum()),
        "text_unchanged": unchanged_text,
        "targets_unchanged": unchanged_targets,
        "empty_subject_after": int(labelled["subject"].eq("").sum()),
        "empty_body_after": int(labelled["body"].eq("").sum()),
        "class_counts_before": {
            str(k): int(v) for k, v in original["target"].value_counts().sort_index().items()
        },
        "class_counts_after": {
            str(k): int(v) for k, v in labelled["target"].value_counts().sort_index().items()
        },
    }
    (PATHS.results / "data_audit.json").write_text(
        json.dumps(audit, ensure_ascii=False, indent=2), encoding="utf-8"
    )


def make_word_tfidf(max_features: int) -> TfidfVectorizer:
    return TfidfVectorizer(
        lowercase=True,
        strip_accents="unicode",
        sublinear_tf=True,
        min_df=2,
        max_df=0.98,
        ngram_range=(1, 2),
        max_features=max_features,
        dtype=np.float32,
    )


def make_feature_extractor(kind: str, config: ExperimentConfig):
    """Build one of the representations used in the controlled ablation."""

    if kind == "raw":
        return make_word_tfidf(config.word_features)
    if kind == "body":
        return make_word_tfidf(config.body_features)
    if kind == "dual":
        return ColumnTransformer(
            [
                (
                    "subject",
                    TfidfVectorizer(
                        min_df=2,
                        ngram_range=(1, 2),
                        sublinear_tf=True,
                        max_features=config.subject_features,
                        dtype=np.float32,
                    ),
                    "subject",
                ),
                ("body", make_word_tfidf(config.body_features), "body"),
            ],
            transformer_weights={"subject": 2.0, "body": 1.0},
        )
    if kind == "hybrid":
        # Innovation: word n-grams express semantic tokens, while character
        # n-grams are robust to word forms, spelling variation and noisy headers.
        return FeatureUnion(
            [
                ("word", make_word_tfidf(config.word_features)),
                (
                    "char",
                    TfidfVectorizer(
                        analyzer="char_wb",
                        ngram_range=(3, 5),
                        min_df=3,
                        max_features=config.char_features,
                        sublinear_tf=True,
                        dtype=np.float32,
                    ),
                ),
            ],
            transformer_weights={"word": 1.0, "char": config.hybrid_char_weight},
        )
    raise ValueError(f"Unknown representation: {kind}")


def feature_input(frame: pd.DataFrame, kind: str):
    if kind == "dual":
        return frame
    if kind == "body":
        return frame["body"]
    return frame["text"]


def metric_row(
    algorithm: str,
    representation: str,
    parameters: dict[str, Any],
    y_true,
    y_pred,
    fit_seconds: float,
) -> dict[str, Any]:
    return {
        "algorithm": algorithm,
        "representation": representation,
        "parameters": json.dumps(parameters, sort_keys=True),
        "accuracy": accuracy_score(y_true, y_pred),
        "macro_f1": f1_score(y_true, y_pred, average="macro"),
        "fit_seconds": fit_seconds,
    }


def fit_and_score_pipeline(
    algorithm: str,
    representation: str,
    parameters: dict[str, Any],
    estimator,
    train: pd.DataFrame,
    validation: pd.DataFrame,
    config: ExperimentConfig,
) -> tuple[dict[str, Any], Pipeline, np.ndarray]:
    pipeline = Pipeline(
        [
            ("features", make_feature_extractor(representation, config)),
            ("classifier", estimator),
        ]
    )
    started = time.perf_counter()
    pipeline.fit(feature_input(train, representation), train["target"])
    prediction = pipeline.predict(feature_input(validation, representation))
    result = metric_row(
        algorithm,
        representation,
        parameters,
        validation["target"],
        prediction,
        time.perf_counter() - started,
    )
    print(
        f"{algorithm:15s} {representation:7s} {parameters!s:18s} "
        f"accuracy={result['accuracy']:.4f} macro-F1={result['macro_f1']:.4f}"
    )
    return result, pipeline, prediction


def run_classical_experiments(
    train: pd.DataFrame,
    validation: pd.DataFrame,
    config: ExperimentConfig,
) -> tuple[list[dict[str, Any]], dict[tuple, tuple[Pipeline, np.ndarray]]]:
    """Compare algorithms, hyperparameters, and controlled representations."""

    results: list[dict[str, Any]] = []
    fitted: dict[tuple, tuple[Any, np.ndarray]] = {}

    # Algorithm 1: Multinomial Naive Bayes with alpha comparison.
    for alpha in (0.1, 1.0, 10.0):
        result, pipeline, prediction = fit_and_score_pipeline(
            "MultinomialNB",
            "raw",
            {"alpha": alpha},
            MultinomialNB(alpha=alpha),
            train,
            validation,
            config,
        )
        results.append(result)
        fitted[("MultinomialNB", "raw", alpha)] = pipeline, prediction

    # Algorithm 2: linear SVM.  LinearSVC is the scalable linear SVM
    # implementation suited to high-dimensional sparse TF-IDF matrices.
    for c_value in (0.1, 0.5, 1.0, 2.0, 10.0):
        result, pipeline, prediction = fit_and_score_pipeline(
            "LinearSVM",
            "raw",
            {"C": c_value},
            LinearSVC(C=c_value, random_state=config.seed, dual="auto"),
            train,
            validation,
            config,
        )
        results.append(result)
        fitted[("LinearSVM", "raw", c_value)] = pipeline, prediction

    # Algorithm 3: logistic regression, included because it is introduced in
    # the assignment handout and provides another linear-model comparison.
    for c_value in (0.1, 1.0, 10.0):
        result, pipeline, prediction = fit_and_score_pipeline(
            "LogisticRegression",
            "raw",
            {"C": c_value},
            LogisticRegression(
                C=c_value,
                max_iter=2_000,
                solver="lbfgs",
                random_state=config.seed,
            ),
            train,
            validation,
            config,
        )
        results.append(result)
        fitted[("LogisticRegression", "raw", c_value)] = pipeline, prediction

    raw_svm_rows = [
        row for row in results
        if row["algorithm"] == "LinearSVM" and row["representation"] == "raw"
    ]
    best_raw_c = json.loads(max(raw_svm_rows, key=lambda row: row["macro_f1"])["parameters"])["C"]

    # Controlled ablation: same split and classifier; change only the input
    # representation. Body and dual use the best raw C. Hybrid has its own C
    # comparison because its feature dimensionality and regularization differ.
    for representation in ("body", "dual"):
        result, pipeline, prediction = fit_and_score_pipeline(
            "LinearSVM",
            representation,
            {"C": best_raw_c},
            LinearSVC(C=best_raw_c, random_state=config.seed, dual="auto"),
            train,
            validation,
            config,
        )
        results.append(result)
        fitted[("LinearSVM", representation, best_raw_c)] = pipeline, prediction

    hybrid_features = make_feature_extractor("hybrid", config)
    feature_start = time.perf_counter()
    hybrid_train = hybrid_features.fit_transform(train["text"])
    hybrid_validation = hybrid_features.transform(validation["text"])
    feature_seconds = time.perf_counter() - feature_start
    for c_value in (0.3, 0.5, 0.8, 1.0):
        classifier = LinearSVC(C=c_value, random_state=config.seed, dual="auto")
        fit_start = time.perf_counter()
        classifier.fit(hybrid_train, train["target"])
        prediction = classifier.predict(hybrid_validation)
        result = metric_row(
            "LinearSVM",
            "hybrid",
            {"C": c_value},
            validation["target"],
            prediction,
            feature_seconds + time.perf_counter() - fit_start,
        )
        results.append(result)
        fitted[("LinearSVM", "hybrid", c_value)] = classifier, prediction
        parameter_text = str({"C": c_value})
        print(
            f"{'LinearSVM':15s} {'hybrid':7s} {parameter_text:18s} "
            f"accuracy={result['accuracy']:.4f} macro-F1={result['macro_f1']:.4f}"
        )

    return results, fitted


def train_mlp_with_history(
    train: pd.DataFrame,
    validation: pd.DataFrame,
    config: ExperimentConfig,
) -> tuple[dict[str, Any], pd.DataFrame, np.ndarray]:
    """Train an MLP explicitly by epoch and record measured cross-entropy."""

    vectorizer = make_word_tfidf(config.mlp_features)
    x_train = vectorizer.fit_transform(train["text"])
    x_validation = vectorizer.transform(validation["text"])
    y_train = train["target"].to_numpy()
    y_validation = validation["target"].to_numpy()

    model = MLPClassifier(
        hidden_layer_sizes=(config.mlp_hidden_units,),
        activation=config.mlp_activation,
        solver="adam",
        alpha=config.mlp_alpha,
        batch_size="auto",
        learning_rate_init=1e-3,
        max_iter=1,
        random_state=config.seed,
    )
    generator = np.random.default_rng(config.seed)
    history: list[dict[str, float]] = []
    best_loss = np.inf
    best_model = None
    best_epoch = 0
    epochs_without_improvement = 0
    started = time.perf_counter()

    for epoch in range(1, config.mlp_max_epochs + 1):
        order = generator.permutation(len(y_train))
        first_batch = epoch == 1
        for start in range(0, len(order), config.batch_size):
            batch = order[start : start + config.batch_size]
            class_argument = {"classes": LABELS} if first_batch else {}
            model.partial_fit(x_train[batch], y_train[batch], **class_argument)
            first_batch = False

        train_probability = model.predict_proba(x_train)
        validation_probability = model.predict_proba(x_validation)
        train_prediction = LABELS[np.argmax(train_probability, axis=1)]
        validation_prediction = LABELS[np.argmax(validation_probability, axis=1)]
        epoch_result = {
            "epoch": epoch,
            "train_loss": log_loss(y_train, train_probability, labels=LABELS),
            "validation_loss": log_loss(
                y_validation, validation_probability, labels=LABELS
            ),
            "train_accuracy": accuracy_score(y_train, train_prediction),
            "validation_accuracy": accuracy_score(
                y_validation, validation_prediction
            ),
            "validation_macro_f1": f1_score(
                y_validation, validation_prediction, average="macro"
            ),
        }
        history.append(epoch_result)
        print(
            f"MLP epoch {epoch:02d}: train_loss={epoch_result['train_loss']:.4f} "
            f"validation_loss={epoch_result['validation_loss']:.4f} "
            f"macro-F1={epoch_result['validation_macro_f1']:.4f}"
        )

        if epoch_result["validation_loss"] < best_loss - 1e-4:
            best_loss = epoch_result["validation_loss"]
            best_epoch = epoch
            best_model = copy.deepcopy(model)
            epochs_without_improvement = 0
        else:
            epochs_without_improvement += 1
            if epochs_without_improvement >= config.mlp_patience:
                print(f"Early stopping: best epoch was {best_epoch}")
                break

    assert best_model is not None
    best_prediction = best_model.predict(x_validation)
    result = metric_row(
        "MLP",
        "raw",
        {"hidden_units": config.mlp_hidden_units, "best_epoch": best_epoch},
        y_validation,
        best_prediction,
        time.perf_counter() - started,
    )
    return result, pd.DataFrame(history), best_prediction


def save_plots(
    results: pd.DataFrame,
    history: pd.DataFrame,
    validation_labels,
    best_prediction,
) -> None:
    """Create the plots required to explain process and results."""

    plt.style.use("seaborn-v0_8-whitegrid")

    figure, axis = plt.subplots(figsize=(8, 5))
    axis.plot(history["epoch"], history["train_loss"], "o-", label="Training loss")
    axis.plot(
        history["epoch"],
        history["validation_loss"],
        "s-",
        label="Validation loss",
    )
    best_epoch = int(history.loc[history["validation_loss"].idxmin(), "epoch"])
    axis.axvline(best_epoch, color="gray", linestyle="--", label=f"Best epoch = {best_epoch}")
    axis.set(xlabel="Epoch", ylabel="Cross-entropy loss", title="MLP learning curve")
    axis.legend()
    figure.tight_layout()
    figure.savefig(PATHS.figures / "loss_curve.png", dpi=220)
    plt.close(figure)

    best_by_algorithm = results.loc[results.groupby("algorithm")["macro_f1"].idxmax()]
    figure, axis = plt.subplots(figsize=(7, 4.5))
    bars = axis.bar(
        best_by_algorithm["algorithm"],
        best_by_algorithm["macro_f1"],
        color=["#4c78a8", "#f58518", "#54a24b", "#e45756"],
    )
    axis.set_ylim(max(0, best_by_algorithm["macro_f1"].min() - 0.08), 1)
    axis.set(ylabel="Validation macro-F1", title="Best result by algorithm")
    for bar, value in zip(bars, best_by_algorithm["macro_f1"]):
        axis.text(bar.get_x() + bar.get_width() / 2, value + 0.002, f"{value:.4f}", ha="center")
    figure.tight_layout()
    figure.savefig(PATHS.figures / "model_comparison.png", dpi=220)
    plt.close(figure)

    svm_rows = results[results["algorithm"] == "LinearSVM"]
    ablation = svm_rows.loc[svm_rows.groupby("representation")["macro_f1"].idxmax()]
    figure, axis = plt.subplots(figsize=(7, 4.5))
    bars = axis.bar(
        ablation["representation"],
        ablation["macro_f1"],
        color=["#4c78a8", "#f58518", "#54a24b", "#72b7b2"],
    )
    axis.set_ylim(max(0, ablation["macro_f1"].min() - 0.05), 1)
    axis.set(ylabel="Validation macro-F1", title="Feature representation ablation")
    for bar, value in zip(bars, ablation["macro_f1"]):
        axis.text(bar.get_x() + bar.get_width() / 2, value + 0.001, f"{value:.4f}", ha="center", fontsize=9)
    figure.tight_layout()
    figure.savefig(PATHS.figures / "ablation_comparison.png", dpi=220)
    plt.close(figure)

    matrix = confusion_matrix(
        validation_labels, best_prediction, labels=LABELS, normalize="true"
    )
    figure, axis = plt.subplots(figsize=(8, 7))
    image = axis.imshow(matrix, cmap="Blues", vmin=0, vmax=1)
    figure.colorbar(image, ax=axis)
    axis.set_xticks(LABELS)
    axis.set_yticks(LABELS)
    for row in range(10):
        for column in range(10):
            axis.text(
                column,
                row,
                f"{matrix[row, column]:.2f}",
                ha="center",
                va="center",
                fontsize=7,
                color="white" if matrix[row, column] > 0.5 else "black",
            )
    axis.set(
        xlabel="Predicted label",
        ylabel="True label",
        title="Validation confusion matrix (row-normalized)",
    )
    figure.tight_layout()
    figure.savefig(PATHS.figures / "confusion_matrix.png", dpi=220)
    plt.close(figure)


def save_environment_information(config: ExperimentConfig) -> None:
    class MemoryStatus(ctypes.Structure):
        _fields_ = [
            ("length", ctypes.c_ulong),
            ("memory_load", ctypes.c_ulong),
            ("total_physical", ctypes.c_ulonglong),
            ("available_physical", ctypes.c_ulonglong),
            ("total_page_file", ctypes.c_ulonglong),
            ("available_page_file", ctypes.c_ulonglong),
            ("total_virtual", ctypes.c_ulonglong),
            ("available_virtual", ctypes.c_ulonglong),
            ("available_extended_virtual", ctypes.c_ulonglong),
        ]

    memory_gb = None
    if sys.platform == "win32":
        status = MemoryStatus()
        status.length = ctypes.sizeof(status)
        if ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(status)):
            memory_gb = round(status.total_physical / (1024 ** 3), 2)

    def file_hash(path: Path) -> str:
        digest = hashlib.sha256()
        with path.open("rb") as stream:
            for block in iter(lambda: stream.read(1024 * 1024), b""):
                digest.update(block)
        return digest.hexdigest()

    information = {
        "python": sys.version,
        "platform": platform.platform(),
        "processor": platform.processor() or os.environ.get("PROCESSOR_IDENTIFIER"),
        "logical_cpu_count": os.cpu_count(),
        "physical_memory_gb": memory_gb,
        "numpy": np.__version__,
        "pandas": pd.__version__,
        "scikit_learn": sklearn.__version__,
        "random_seed": config.seed,
        "train_sha256": file_hash(PATHS.train_csv),
    }
    (PATHS.results / "environment.json").write_text(
        json.dumps(information, indent=2), encoding="utf-8"
    )


def main() -> None:
    arguments = parse_arguments()
    config = (
        ExperimentConfig(
            word_features=12_000,
            char_features=8_000,
            subject_features=3_000,
            body_features=10_000,
            mlp_features=5_000,
            mlp_max_epochs=4,
            mlp_patience=2,
        )
        if arguments.quick
        else ExperimentConfig()
    )
    random.seed(config.seed)
    np.random.seed(config.seed)
    create_directories()
    save_environment_information(config)

    # The official test set is not loaded anywhere in the development phase.
    labelled_data = load_labelled_data()
    save_data_audit(labelled_data)
    all_indices = np.arange(len(labelled_data))
    train_indices, validation_indices = train_test_split(
        all_indices,
        test_size=config.validation_size,
        random_state=config.seed,
        stratify=labelled_data["target"],
    )
    train = labelled_data.iloc[train_indices].copy()
    validation = labelled_data.iloc[validation_indices].copy()
    np.savez(
        PATHS.results / "split_indices.npz",
        train_indices=train_indices,
        validation_indices=validation_indices,
    )
    print(
        f"labelled={len(labelled_data)}, train={len(train)}, "
        f"validation={len(validation)}; official test remains sealed"
    )

    rows, fitted = run_classical_experiments(train, validation, config)
    mlp_row, mlp_history, mlp_prediction = train_mlp_with_history(
        train, validation, config
    )
    rows.append(mlp_row)
    results = pd.DataFrame(rows).sort_values(
        ["accuracy", "macro_f1"], ascending=False
    ).reset_index(drop=True)
    best_row = results.iloc[0]

    if best_row["algorithm"] == "MLP":
        best_validation_prediction = mlp_prediction
    else:
        parameters = json.loads(best_row["parameters"])
        value = parameters.get("C", parameters.get("alpha"))
